srapi_scancode_t srapi_input_evdev_to_scancode(uint16_t evdev_code) {
    if (evdev_code >= 256) {
        return SRAPI_SCANCODE_UNKNOWN;
    }
    return k_evdev_map[evdev_code];
}

uint32_t srapi_input_scancode_to_keymod(srapi_scancode_t sc) {
    switch (sc) {
        case SRAPI_SCANCODE_LSHIFT:   return SRAPI_KMOD_LSHIFT;
        case SRAPI_SCANCODE_RSHIFT:   return SRAPI_KMOD_RSHIFT;
        case SRAPI_SCANCODE_LCTRL:    return SRAPI_KMOD_LCTRL;
        case SRAPI_SCANCODE_RCTRL:    return SRAPI_KMOD_RCTRL;
        case SRAPI_SCANCODE_LALT:     return SRAPI_KMOD_LALT;
        case SRAPI_SCANCODE_RALT:     return SRAPI_KMOD_RALT;
        case SRAPI_SCANCODE_LGUI:     return SRAPI_KMOD_LGUI;
        case SRAPI_SCANCODE_RGUI:     return SRAPI_KMOD_RGUI;
        default:                      return 0;
    }
}

const char *srapi_scancode_name(srapi_scancode_t scancode) {
    if ((int)scancode < 0 || (int)scancode >= SRAPI_SCANCODE_COUNT) {
        return "Unknown";
    }
    const char *name = k_scancode_names[scancode];
    return name != NULL ? name : "Unknown";
}
