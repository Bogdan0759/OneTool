const uint8_t *ranal_font_glyph_(char c) {
    if (c < 32 || c > 126) {
        c = '?';
    }
    return k_glyphs[c - 32];
}

const uint8_t *ranal_font_glyph(char c) {
    return ranal_font_glyph_(c);
}

const uint8_t *ranal_font_glyph_u(uint32_t cp) {
    if (cp < 0x80u) {
        if (cp < 32u || cp > 126u) cp = '?';
        return k_glyphs[cp - 32u];
    }
    if (cp == 0x0401u) return k_glyph_yo_upper;
    if (cp == 0x0451u) return k_glyph_yo_lower;
    if (cp >= 0x0410u && cp <= 0x042Fu) return k_cyrillic_upper[cp - 0x0410u];
    if (cp >= 0x0430u && cp <= 0x044Fu) return k_cyrillic_lower[cp - 0x0430u];
    return k_glyphs['?' - 32];
}

int ranal_utf8_decode(const char *s, uint32_t *out_cp) {
    if (s == NULL || s[0] == '\0') {
        if (out_cp != NULL) *out_cp = 0;
        return 0;
    }
    const unsigned char *u = (const unsigned char *)s;
    unsigned char b0 = u[0];
    uint32_t cp;
    int len;
    if (b0 < 0x80u) {
        cp = b0; len = 1;
    } else if ((b0 & 0xE0u) == 0xC0u) {
        if ((u[1] & 0xC0u) != 0x80u) { if (out_cp) *out_cp = 0xFFFD; return 1; }
        cp = ((uint32_t)(b0 & 0x1Fu) << 6) | (uint32_t)(u[1] & 0x3Fu);
        len = 2;
    } else if ((b0 & 0xF0u) == 0xE0u) {
        if ((u[1] & 0xC0u) != 0x80u || (u[2] & 0xC0u) != 0x80u) {
            if (out_cp) *out_cp = 0xFFFD; return 1;
        }
        cp = ((uint32_t)(b0 & 0x0Fu) << 12)
           | ((uint32_t)(u[1] & 0x3Fu) << 6)
           |  (uint32_t)(u[2] & 0x3Fu);
        len = 3;
    } else if ((b0 & 0xF8u) == 0xF0u) {
        if ((u[1] & 0xC0u) != 0x80u || (u[2] & 0xC0u) != 0x80u || (u[3] & 0xC0u) != 0x80u) {
            if (out_cp) *out_cp = 0xFFFD; return 1;
        }
        cp = ((uint32_t)(b0 & 0x07u) << 18)
           | ((uint32_t)(u[1] & 0x3Fu) << 12)
           | ((uint32_t)(u[2] & 0x3Fu) << 6)
           |  (uint32_t)(u[3] & 0x3Fu);
        len = 4;
    } else {
        if (out_cp) *out_cp = 0xFFFD;
        return 1;
    }
    if (out_cp) *out_cp = cp;
    return len;
}

int32_t ranal_text_width(const char *text) {
    if (text == NULL) return 0;
    int32_t cells = 0;
    const char *p = text;
    while (*p != '\0') {
        uint32_t cp;
        int n = ranal_utf8_decode(p, &cp);
        if (n <= 0) break;
        p += n;
        cells++;
    }
    return cells * RANAL_FONT_W;
}

int32_t ranal_text_height(void) {
    return RANAL_FONT_H;
}

